create role anon;
create role authenticated;
create role service_role bypassrls;
create table public.sources(id uuid primary key default gen_random_uuid());
create table public.products(
  id uuid primary key default gen_random_uuid(),
  canonical_name_ja text not null,
  canonical_name_en text,
  manufacturer text,
  jan_code text,
  model_number text,
  source_id uuid references public.sources(id) on delete set null,
  image_status text check (image_status in ('pending','found','missing','error')),
  source_product_key text,
  product_type text,
  product_status text not null default 'unknown'
    check (product_status in ('announced','preorder','active','discontinued','unknown')),
  identification_confidence numeric(5,4) check (identification_confidence between 0 and 1),
  source_last_checked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  character_names text[] not null default '{}',
  metadata jsonb not null default '{}'
);
create unique index fixture_product_barcode_unique on public.products(jan_code)
  where jan_code is not null and jan_code<>'';
create unique index fixture_product_source_unique on public.products(source_id,source_product_key)
  where source_id is not null and source_product_key is not null;
create index fixture_product_key_idx on public.products(source_product_key);
create function public.set_updated_at() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end
$$;
create trigger fixture_product_updated_at before update on public.products
  for each row execute function public.set_updated_at();
create table public.api_events(
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  event_type text not null,
  endpoint text,
  product_id text,
  payer_hash text,
  amount_atomic bigint,
  amount_usdc numeric(18,6),
  payment_network text,
  transaction_hash text,
  metadata jsonb not null default '{}'
);
alter table public.products enable row level security;
alter table public.api_events enable row level security;
grant select,insert,update on public.products to service_role;
grant usage,select on all sequences in schema public to service_role;
grant select,insert,delete on public.api_events to service_role;
